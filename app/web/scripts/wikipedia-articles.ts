// Writes src/articles.ts: each candidate's Wikipedia article in every language the site is written in. It starts
// from the French titles in config/sources.yaml and follows each article's interlanguage links, which Wikidata
// keeps, so a candidate gets an article in a language only when that Wikipedia has one about them.
//
// Run it with `moon run web:articles` when config/sources.yaml gains or changes a candidate.

import { readFileSync, writeFileSync } from "node:fs"
import { parse } from "yaml"

const ROOT = new URL("../../../", import.meta.url)
const OUTPUT = new URL("../src/articles.ts", import.meta.url)
const USER_AGENT = "fr2027-forecaster (https://github.com/Hebilicious/fr2027-forecaster)"

/** Each site locale with the Wikipedia that serves it, and the path that opens an article in its script. */
const WIKIS = {
  "en-GB": { wiki: "en", path: "wiki" },
  de: { wiki: "de", path: "wiki" },
  it: { wiki: "it", path: "wiki" },
  "es-ES": { wiki: "es", path: "wiki" },
  "pt-PT": { wiki: "pt", path: "wiki" },
  pl: { wiki: "pl", path: "wiki" },
  ru: { wiki: "ru", path: "wiki" },
  ja: { wiki: "ja", path: "wiki" },
  ko: { wiki: "ko", path: "wiki" },
  // The Chinese Wikipedia is one wiki in several scripts; this path shows it in simplified characters.
  "zh-Hans": { wiki: "zh", path: "zh-hans" },
  th: { wiki: "th", path: "wiki" },
} as const

interface Sources {
  candidates: Record<string, { wikipedia: string | null }>
}

interface LangLinksResponse {
  query?: {
    normalized?: { from: string; to: string }[]
    redirects?: { from: string; to: string }[]
    pages: Record<string, { title: string; missing?: string; langlinks?: { lang: string; "*": string }[] }>
  }
}

const articleUrl = (wiki: string, path: string, title: string) =>
  `https://${wiki}.wikipedia.org/${path}/${encodeURIComponent(title.replaceAll(" ", "_"))}`

const sources = parse(readFileSync(new URL("config/sources.yaml", ROOT), "utf8")) as Sources
const titles = Object.fromEntries(
  Object.entries(sources.candidates).flatMap(([id, c]) =>
    c.wikipedia ? [[id, c.wikipedia.replaceAll("_", " ")]] : [],
  ),
)

/** The French titles that have an article, and for each its title on `wiki` when that Wikipedia has one too. */
async function linksTo(wiki: string): Promise<{ found: Set<string>; links: Map<string, string> }> {
  const url = new URL("https://fr.wikipedia.org/w/api.php")
  url.search = new URLSearchParams({
    action: "query",
    format: "json",
    redirects: "1",
    prop: "langlinks",
    lllang: wiki,
    lllimit: "max",
    titles: Object.values(titles).join("|"),
  }).toString()
  const response = await fetch(url, { headers: { "User-Agent": USER_AGENT } })
  if (!response.ok) throw new Error(`fr.wikipedia.org answered ${response.status} for ${wiki}`)
  const { query } = (await response.json()) as LangLinksResponse
  if (!query) throw new Error(`fr.wikipedia.org sent no pages for ${wiki}`)

  // The API answers under the article's own title: follow normalisation and redirects back to ours.
  const renamed = new Map([...(query.normalized ?? []), ...(query.redirects ?? [])].map((r) => [r.from, r.to]))
  const resolve = (title: string) => {
    let current = title
    while (renamed.has(current)) current = renamed.get(current)!
    return current
  }
  const byPage = new Map(Object.values(query.pages).map((p) => [p.title, p]))
  const found = new Set<string>()
  const links = new Map<string, string>()
  for (const title of Object.values(titles)) {
    const page = byPage.get(resolve(title))
    if (!page || page.missing !== undefined) continue
    found.add(title)
    const link = page.langlinks?.[0]?.["*"]
    if (link) links.set(title, link)
  }
  return { found, links }
}

const answers = Object.fromEntries(
  await Promise.all(Object.entries(WIKIS).map(async ([locale, { wiki }]) => [locale, await linksTo(wiki)] as const)),
)
const links = Object.fromEntries(Object.entries(answers).map(([locale, answer]) => [locale, answer.links]))
const found = answers["en-GB"]!.found

// A title in config/sources.yaml that French Wikipedia lacks gets no link at all, rather than a dead one.
for (const [id, title] of Object.entries(titles)) {
  if (!found.has(title)) console.warn(`${id}: French Wikipedia has no article "${title}"; no link written`)
}

const entries = Object.entries(titles)
  .filter(([, title]) => found.has(title))
  .toSorted(([a], [b]) => a.localeCompare(b))
  .map(([id, title]) => {
    const urls = [`    fr: ${JSON.stringify(articleUrl("fr", "wiki", title))},`]
    for (const [locale, { wiki, path }] of Object.entries(WIKIS)) {
      const local = links[locale]?.get(title)
      if (local) urls.push(`    ${JSON.stringify(locale)}: ${JSON.stringify(articleUrl(wiki, path, local))},`)
    }
    return `  ${id}: {\n${urls.join("\n")}\n  },`
  })

writeFileSync(
  OUTPUT,
  `// Generated by scripts/wikipedia-articles.ts (moon run web:articles); do not edit by hand.
// Each candidate's Wikipedia article: the French one from config/sources.yaml, and the article that the French one
// links to in each other language the site is written in, where that Wikipedia has one.

import type { Locale } from "./locales"

export const ARTICLES: Readonly<Record<string, { fr: string } & Partial<Record<Locale, string>>>> = {
${entries.join("\n")}
}
`,
)
console.log(`wrote ${entries.length} candidates to src/articles.ts`)
